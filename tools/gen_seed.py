"""Один раз генерирует синтетические обращения для демо: data/seed.json.

Запуск: AI_KEY=... python -m tools.gen_seed
"""

import json
import random
from pathlib import Path

from razbor import llm

GROUPS = [
    "справки (об обучении, для военкомата, для налогового вычета), расписание, пересдачи, ведомости",
    "стипендия не пришла, материальная помощь, оплата обучения и просрочка, налоговый вычет",
    "перевод на другое направление, академический отпуск, восстановление, отчисление",
    "нет доступа к личному кабинету, СДО, почте, пропуск не работает; общежитие: заселение, сломанный кран, оплата",
    "сотрудники вуза: справка с места работы, отпуск; жалобы на грубость сотрудника; обращения не по адресу",
]

PROMPT = """Придумай 11 разных письменных обращений в российский вуз на тему: %s.
Это синтетические данные для демонстрации, без реальных имён (можно вымышленные имя и группа).
Разнообразие обязательно: короткие и длинные, вежливые и раздражённые, с опечатками,
2 срочных (срок истекает завтра-послезавтра), 1 с угрозой пожаловаться ректору или
в министерство, 1-2 отправлены явно не в то подразделение, 1 повторное («пишу третий раз»).
Верни только JSON-массив объектов {"channel": "Почта"|"Личный кабинет"|"Telegram-бот"|"Бумажное заявление",
"author": "Студент 2 курса"|"Магистрант"|"Сотрудник кафедры"|..., "text": текст обращения}."""


def main() -> None:
    out: list[dict[str, str]] = []
    for group in GROUPS:
        raw = llm.chat([{"role": "user", "content": PROMPT % group}], max_tokens=4000)
        start, end = raw.find("["), raw.rfind("]")
        items = json.loads(raw[start : end + 1])
        out += [{k: str(i[k]) for k in ("channel", "author", "text")} for i in items]
        print(group[:30], len(items))
    random.Random(7).shuffle(out)
    path = Path(__file__).resolve().parent.parent / "data" / "seed.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print("total", len(out))


if __name__ == "__main__":
    main()
